const span = (word: string, tip: string) => `<span class="term" tabindex="0" data-tip="${tip}">${word}</span>`;

// 태그 밖의 글자에서만, 용어마다 처음 나온 곳 하나에만 풀이를 붙인다
export function annotateRun(html: string): string {
  const used = new Set<string>();
  return html
    .split(/(<[^>]+>)/)
    .map((part) => {
      if (part.startsWith('<')) return part;
      let out = part;
      // 긴 용어부터 바꾸고, 바꾼 자리는 표시해 두어 짧은 용어(포스아웃 안의 포스 등)가 다시 건드리지 않게 한다
      const slots: string[] = [];
      const hold = (s: string) => `\u0000${slots.push(s) - 1}\u0000`;
      for (const [word, tip] of TERMS) {
        if (used.has(word)) continue;
        const i = out.indexOf(word);
        if (i < 0) continue;
        used.add(word);
        out = out.slice(0, i) + hold(span(word, tip)) + out.slice(i + word.length);
      }
      return out.replace(/\u0000(\d+)\u0000/g, (_, n) => slots[Number(n)]);
    })
    .join('');
}
